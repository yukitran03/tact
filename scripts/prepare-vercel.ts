/**
 * Embeds the Preact bundle + HTML/CSS/favicon into src/server/embedded.ts so the
 * Vercel function does not need filesystem access to web/. Also refreshes the
 * JSON fixture import used on cold start.
 */
import { mkdirSync, writeFileSync, readFileSync, cpSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const pub = join(root, "public");
mkdirSync(pub, { recursive: true });

const out = await Bun.build({
  entrypoints: [join(root, "web", "app.tsx")],
  minify: true,
  target: "browser",
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
});
if (!out.success) {
  for (const l of out.logs) console.error(l);
  process.exit(1);
}
const appJs = await out.outputs[0].text();
const html = readFileSync(join(root, "web", "index.html"), "utf8");
const css = readFileSync(join(root, "web", "styles.css"), "utf8");
const favicon = readFileSync(join(root, "web", "favicon.svg"), "utf8");
const fixture = readFileSync(join(root, "data", "demo-fixture.json"), "utf8");

writeFileSync(join(pub, "app.js"), appJs);
cpSync(join(root, "web", "index.html"), join(pub, "index.html"));
cpSync(join(root, "web", "styles.css"), join(pub, "styles.css"));
cpSync(join(root, "web", "favicon.svg"), join(pub, "favicon.svg"));
writeFileSync(join(root, "src", "server", "demo-fixture.json"), fixture);

const esc = (s: string) => JSON.stringify(s);
writeFileSync(
  join(root, "src", "server", "embedded.ts"),
  `/** Generated by scripts/prepare-vercel.ts — do not edit. */\n` +
    `export const EMBEDDED_HTML = ${esc(html)};\n` +
    `export const EMBEDDED_CSS = ${esc(css)};\n` +
    `export const EMBEDDED_APP_JS = ${esc(appJs)};\n` +
    `export const EMBEDDED_FAVICON = ${esc(favicon)};\n`,
);

console.log(`embedded: html=${html.length} css=${css.length} js=${appJs.length} favicon=${favicon.length}`);
